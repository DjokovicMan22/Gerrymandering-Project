"""A reversible, explicitly defined *exploratory* local map-sampling kernel.

Unlike an ordinary ReCom proposal with unknown proposal probabilities, this
boundary-edge Metropolis--Hastings kernel has a tractable proposal distribution.

State: a *labeled* precinct-to-district assignment satisfying district
contiguity on the augmented graph, population tolerance, and optional
geographic source-group caps.

Each step chooses uniformly from CURRENT boundary edges. With fixed mixture
probability it either:
  (flip) orients the edge at random and assigns that endpoint to its neighbor's
      district. q(x,y) = n_x(node,new_label) / (2 * cuts(x)).
  (swap) exchanges the two endpoint district labels.
      q(x,y) = 1 / cuts(x).
For both kinds the reverse candidate is tested and accepted with probability
min(1, q(y,x)/q(x,y)); invalid moves become explicit holding self-loops.
The constant mixture probability cancels in the MH ratio, since a one-node flip
cannot be generated by a two-node swap and vice versa.

Detailed balance with respect to the *uniform measure on each finite
communicating class of feasible labeled maps* follows algebraically. This does
NOT prove that the chain can reach every legal map, that the target is the
correct policy-science measure, or that it mixes in a practical time.
"""
from __future__ import annotations

import math
import random
from collections import Counter
from dataclasses import dataclass
from typing import Any

from gerrychain.constraints import contiguous

from .geographic import GeographicCaps, GeographicEvaluator
from .partition import ideal_population, max_population_deviation


def _sort_boundary_edge(edge: tuple) -> tuple[str, str]:
    """Deterministic sorting key for a graph with arbitrary node identifiers."""
    a, b = (str(node) for node in edge)
    return (a, b) if a <= b else (b, a)


def boundary_edges(partition: Any) -> tuple[tuple, ...]:
    edges = tuple(sorted(partition["cut_edges"], key=_sort_boundary_edge))
    if len(edges) != len(set(frozenset(edge) for edge in edges)):
        raise ValueError("Duplicate undirected boundary edges invalidate MH probabilities")
    return edges


def neighboring_label_count(graph: Any, assignment: Any, node: Any, label: Any) -> int:
    """Number of graph edges between node and vertices of a given district."""
    return sum(assignment[neighbor] == label for neighbor in graph.neighbors(node))


def mh_probability(q_forward: float, q_reverse: float) -> float:
    """Exact uniform-target MH acceptance factor, with zero reverse moves held."""
    if not math.isfinite(q_forward) or not math.isfinite(q_reverse):
        raise ValueError("Proposal probabilities must be finite")
    if q_forward <= 0 or q_reverse < 0:
        raise ValueError("Invalid proposal probabilities")
    return min(1.0, q_reverse / q_forward)


@dataclass(frozen=True)
class BoundaryMHConfig:
    epsilon: float = 0.005
    seed: int = 1101
    flip_probability: float = 0.5
    max_cut_edges: int | None = 760
    max_split_counties: int | None = 18
    max_split_county_mcd: int | None = 20

    def validate(self) -> None:
        if not 0 < self.epsilon < 1:
            raise ValueError("Population tolerance must be between zero and one")
        if type(self.seed) is not int or not (0 <= self.seed < 2**32):
            raise ValueError("Seed must be a 32-bit nonnegative integer")
        if not 0 < self.flip_probability < 1:
            raise ValueError("Mixing probability must be strictly between zero and one")
        GeographicCaps(self.max_cut_edges, self.max_split_counties,
                       self.max_split_county_mcd)

    @property
    def caps(self) -> GeographicCaps:
        return GeographicCaps(self.max_cut_edges, self.max_split_counties,
                              self.max_split_county_mcd)


@dataclass
class MHStep:
    partition: Any
    move: str
    outcome: str
    q_forward: float = 0.0
    q_reverse: float = 0.0
    acceptance_probability: float = 0.0
    node_changes: int = 0


class BoundaryMH:
    """Metropolis--Hastings over a finite, explicitly constrained labeled-map class.

    Returns exactly one state per proposal, even on rejection. The implemented
    population check is equivalent to fixed statewide ideal +/-epsilon.
    """

    def __init__(self, initial_partition: Any, config: BoundaryMHConfig):
        config.validate()
        self.config = config
        self.rng = random.Random(config.seed)
        self.target = ideal_population(initial_partition)
        self.expected_parts = frozenset(initial_partition.parts)
        self.geography = GeographicEvaluator(initial_partition.graph, config.caps)
        self.counts: Counter = Counter()
        self.graph = initial_partition.graph
        if not self.valid(initial_partition):
            raise ValueError("Starting partition is not feasible for MH kernel")
        if not boundary_edges(initial_partition):
            raise ValueError("No boundary edges: cannot draw a local proposal")

    def valid(self, partition: Any) -> bool:
        """Enforce *all* hard constraints for every proposed accepted state."""
        if frozenset(partition.parts) != self.expected_parts:
            return False
        if max_population_deviation(partition, self.target) > self.config.epsilon + 1e-12:
            return False
        if not contiguous(partition):
            return False
        return self.geography(partition)

    def _population_after(self, current: Any, flips: dict) -> bool:
        """Evaluate population changes without constructing a costly Partition."""
        populations = {district: float(value) for district, value in current["population"].items()}
        for node, target in flips.items():
            source = current.assignment[node]
            if source == target:
                continue
            size = float(self.graph.node_data(node)["TOTPOP"])
            populations[source] -= size
            populations[target] += size
        return bool(populations) and all(
            abs(pop / self.target - 1.0) <= self.config.epsilon + 1e-12
            for pop in populations.values()
        )

    def step(self, current: Any) -> MHStep:
        """Draw exactly one proposal, with explicit MH self-loops on rejection."""
        self.counts["attempted"] += 1
        edges = boundary_edges(current)
        if not edges:
            raise ValueError("No boundary edges at the current partition")
        old_cuts = len(edges)
        u, v = self.rng.choice(edges)
        swap = self.rng.random() >= self.config.flip_probability
        move = "swap" if swap else "flip"
        self.counts[f"{move}_attempted"] += 1
        original_u, original_v = current.assignment[u], current.assignment[v]
        if original_u == original_v:
            raise AssertionError("Cut edge endpoints must have different district labels")

        if swap:
            flips = {u: original_v, v: original_u}
            numerator_forward = 1
        else:
            node, neighbor = (u, v) if self.rng.randrange(2) == 0 else (v, u)
            old_label, target_label = current.assignment[node], current.assignment[neighbor]
            flips = {node: target_label}
            numerator_forward = neighboring_label_count(
                self.graph, current.assignment, node, target_label
            )
        if numerator_forward <= 0:
            raise AssertionError("Selected boundary edge provides a forward move")

        if not self._population_after(current, flips):
            self.counts["population_rejected"] += 1
            return MHStep(current, move, "population_rejected")

        proposed = current.flip(flips)
        if frozenset(proposed.parts) != self.expected_parts or not contiguous(proposed):
            self.counts["contiguity_rejected"] += 1
            return MHStep(current, move, "contiguity_rejected")
        if not self.geography(proposed):
            self.counts["geography_rejected"] += 1
            return MHStep(current, move, "geography_rejected")

        new_cuts = len(proposed["cut_edges"])
        if new_cuts == 0:
            raise AssertionError("A valid multi-district graph must have boundaries")
        if swap:
            numerator_reverse = 1
            q_forward = 1.0 / old_cuts
            q_reverse = 1.0 / new_cuts
        else:
            numerator_reverse = neighboring_label_count(
                self.graph, proposed.assignment, node, old_label
            )
            q_forward = numerator_forward / (2.0 * old_cuts)
            q_reverse = numerator_reverse / (2.0 * new_cuts)

        alpha = mh_probability(q_forward, q_reverse)
        if alpha > 0 and self.rng.random() < alpha:
            self.counts["accepted"] += 1
            self.counts[f"{move}_accepted"] += 1
            return MHStep(proposed, move, "accepted", q_forward, q_reverse,
                          alpha, len(flips))

        self.counts["mh_rejected"] += 1
        return MHStep(current, move, "mh_rejected", q_forward, q_reverse, alpha)

    def conservation_audit(self) -> dict:
        """Require every attempted transition to have exactly one disposition."""
        outcomes = ("accepted", "population_rejected", "contiguity_rejected",
                    "geography_rejected", "mh_rejected")
        counted = sum(self.counts[name] for name in outcomes)
        if counted != self.counts["attempted"]:
            raise AssertionError(f"Missing counted MH step: {counted} / {self.counts['attempted']}")
        if self.counts["flip_attempted"] + self.counts["swap_attempted"] != self.counts["attempted"]:
            raise AssertionError("Move-type attempt counts do not add up")
        return dict(self.counts)
